#!/usr/bin/env bash
# 03 - benchmark environment on the instance.
#
#   bash tools/03-setup-env.sh
#   BENCH_PROFILE=quick bash tools/03-setup-env.sh              # short-run .env
#   BENCH_PROFILE=quick bash tools/03-setup-env.sh --skip-build # ... without rebuilding
#
# Note a profile can also be applied per run by 05-run-benchmark.sh, which
# needs no re-setup at all. Use this only when you want it baked into the
# instance's .env.
#
# Three things, in this order:
#   1. copy the repo to the instance   (nothing else can happen first)
#   2. generate .env                   (setup-host.sh refuses to start without it)
#   3. scripts/setup-host.sh --skip-templates
#
# Templates are deliberately NOT built here - that is 04-provision-templates.sh. Splitting them
# matters because templates are the one part that does not survive a
# reboot, so you re-run 04 on its own far more often than 03.
#
# Everything in step 3 is the repo's own verified installer. This script
# adds no install logic of its own on purpose: duplicating it would mean
# two code paths drifting apart.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

SKIP_BUILD=0
for arg in "$@"; do
  case "${arg}" in
    --skip-build) SKIP_BUILD=1 ;;
    -h|--help)    sed -n '2,20p' "$0"; exit 0 ;;
    *) die "unknown argument: ${arg}
     usage: [BENCH_PROFILE=quick] bash tools/03-setup-env.sh [--skip-build]" ;;
  esac
done

load_config
ensure_ssh_key

PRIVATE_IP="$(state_require PRIVATE_IP)"
[[ "$(state_get DISKS_READY || echo 0)" == "1" ]] || die "disks are not prepared.
     Run: bash tools/02-prepare-disks.sh
     (setup-host.sh would refuse anyway: it checks for XFS with reflink.)"

step "waiting for the instance"
wait_for_ssh 600
wait_for_cloud_init

step "copying the repo"
# rsync is not guaranteed to be on a minimal Ubuntu image, and it is needed
# on BOTH ends.
ssh_run "command -v rsync >/dev/null 2>&1 || {
  sudo apt-get update -qq && sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq rsync
}" >/dev/null
rsync_repo_up

step "generating .env"
# Overrides are PREPENDED, not appended: load_env() in scripts/_lib.sh only
# sets a key that is not already set, so the first occurrence in the file
# wins and anything appended after env.example's own value would be
# silently ignored.
profile="${BENCH_PROFILE:-default}"
case "${profile}" in
  quick)   overrides="${BENCH_ENV_OVERRIDES_QUICK:-}" ;;
  default) overrides="${BENCH_ENV_OVERRIDES:-}" ;;
  *)       die "unknown BENCH_PROFILE=${profile} (use 'default' or 'quick')" ;;
esac

env_tmp="$(mktemp)"
{
  echo "# ---- generated by tools/03-setup-env.sh on $(date -Is) ----"
  echo "# profile: ${profile}"
  echo "REGISTRY=${REGISTRY}"
  echo "AWS_REGION=${AWS_REGION}"
  [[ -n "${S3_BUCKET:-}" ]] && echo "S3_BUCKET=${S3_BUCKET}"
  # CUBE_DATA_DIR must sit on the volume 02-prepare-disks.sh prepared.
  echo "CUBE_DATA_DIR=${DATA_MOUNT}/cubelet"
  if [[ -n "${overrides//[[:space:]]/}" ]]; then
    echo "# ---- overrides from tools/config.env (${profile}) ----"
    while IFS= read -r line; do
      [[ -z "${line//[[:space:]]/}" ]] && continue
      [[ "${line}" =~ ^[[:space:]]*# ]] && continue
      echo "${line}"
    done <<< "${overrides}"
  fi
  echo "# ---- defaults below, from env.example ----"
  cat "${REPO_DIR}/env.example"
} > "${env_tmp}"

# shellcheck disable=SC2046
scp $(_ssh_opts) -q "${env_tmp}" "$(ssh_host):${REMOTE_REPO}/.env"
rm -f "${env_tmp}"
log "wrote ${REMOTE_REPO}/.env (profile: ${profile})"
ssh_run "grep -vE '^#|^\$' ${REMOTE_REPO}/.env | head -20 | sed 's/^/    /'"

step "scripts/setup-host.sh --skip-templates"
# --skip-build is forwarded so a re-run that only changes .env (a different
# BENCH_PROFILE, say) does not rebuild and re-push the container image, which
# is by far the slowest step and produces a byte-identical result.
host_flags="--skip-templates"
if (( SKIP_BUILD )); then
  host_flags+=" --skip-build"
  log "skipping the image build (--skip-build)"
else
  warn "this takes a while: Docker, the CubeSandbox one-click bundle (~400 MB),
     datasets, and a native container image build.
     Re-running only to change .env? Use --skip-build."
fi
# -t so the remote sudo/apt output streams instead of arriving in one lump
# at the end; this step is long enough that silence is indistinguishable
# from a hang.
# shellcheck disable=SC2046
ssh $(_ssh_opts) -t "$(ssh_host)" \
  "cd ${REMOTE_REPO} && sudo bash scripts/setup-host.sh ${host_flags}" \
  || die "setup-host.sh failed. It is idempotent - fix the reported problem and re-run tools/03-setup-env.sh."

step "moving the template rootfs directory onto the data volume"
# Deliberately after the install, not before: the target is inside
# CubeSandbox's install root, and the one-click installer refuses to run when
# that root is non-empty without its own markers. Pre-creating it - which an
# earlier version of 02-prepare-disks.sh did - blocked the install with
# "refusing to wipe install root ... contains no CubeSandbox installation
# markers". So the order is install first, relocate second.
ssh_script "${TOOLS_DIR}/remote/bind-image-dir.sh" "${DATA_MOUNT}" \
  || die "could not relocate the template rootfs directory.
     Template images (~3 GiB each) would fill the root volume instead.
     Inspect: ssh ... 'df -h /; ls -la /usr/local/services/cubetoolbox'"
ssh_run "curl -sf --max-time 5 http://127.0.0.1:3000/health && echo" \
  || die "CubeAPI is not healthy. Check: ssh ... 'sudo bash ${REMOTE_REPO}/scripts/ensure-cube.sh'"

state_set ENV_READY 1
echo >&2
log "Next: bash tools/04-provision-templates.sh   (build the 7 templates)"
